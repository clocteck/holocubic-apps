const assert = require("node:assert/strict");
const {createStore,deferred,response} = require("./store-test-harness.cjs");
const {context:c} = createStore();
const raw = {id:"gold-miner",name:"黄金矿工",version:"1.2.11",catalog_scope:"community"};
const installed = new Map([[raw.id,{id:raw.id,version:raw.version,source:"sd"}]]);
const normalize = (extra={},apps=installed)=>c.normalizeItem({...raw,...extra},apps);

async function main(){
  assert.equal(normalize({author:" 游侠173 "}).publisher,"游侠173");
  assert.equal(normalize({author:"游侠173"},new Map()).publisher,"游侠173");
  assert.equal(normalize({author:"  "}).publisher,"社区开发者");
  assert.equal(normalize({catalog_scope:"official"}).publisher,"Cubic 官方");
  assert.equal(normalize({catalog_scope:"official",author:"Alice"}).verified,true);
  assert.equal(normalize({author:"Alice"}).verified,false);
  assert.equal(c.escapeHtml(normalize({author:'<img src=x onerror="alert(1)">'}).publisher),'&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
  assert.equal(c.parseAppInfoMetadata("\uFEFF# author = wrong\r\n; author = wrong\r\nauthor = 游侠173").author,"游侠173");
  assert.equal(c.parseAppInfoMetadata("author = A=B\nauthor = Final").author,"Final");
  assert.equal(c.parseAppInfoMetadata("author =   ").author,"");
  const metadata = c.parseAppInfoMetadata("name_zh_cn = 本地名称\ncategory = game\ncatalog_scope = official\n__proto__ = bad\nmanifest_url = evil");
  assert.equal(metadata.name_zh_cn,"本地名称");
  assert.equal(metadata.__proto__,undefined);
  assert.equal(metadata.manifest_url,undefined);
  c.state.deviceStatus = "online";
  c.state.system = {installed_apps:[...installed.values()]};
  c.updateNormalizedApps();
  let reads = 0;
  c.fetch = async (url)=>{
    reads++;
    assert.equal(new URL(url,"http://device").searchParams.get("path"),"/sd/apps/gold-miner/app.info");
    return response("author = 游侠173\nname_zh_cn = 本地名称\ncategory = game\ncatalog_scope = official\ndescription_zh_cn = 本地介绍");
  };
  await c.loadInstalledMetadata();
  assert.equal(normalize().publisher,"游侠173");
  assert.equal(normalize({author:"Cloud Author"}).publisher,"Cloud Author");
  assert.equal(c.state.apps[0].name,"本地名称");
  assert.equal(c.state.apps[0].category,"game");
  assert.equal(c.state.apps[0].scope,"official");
  assert.equal(c.state.apps[0].description,"本地介绍");
  await c.loadInstalledMetadata();
  assert.equal(reads,1);
  installed.get(raw.id).version = "1.2.12";
  c.updateNormalizedApps();
  await c.loadInstalledMetadata();
  assert.equal(reads,2,"new versions require fresh metadata");
  c.state.installedMetadata = new Map();
  c.fetch = async ()=>{throw new Error("offline");};
  await c.loadInstalledMetadata();
  assert.equal(normalize().publisher,"社区开发者");
  c.state.installedMetadata = new Map();
  c.fetch = async ()=>response("not found",false);
  await c.loadInstalledMetadata();
  assert.equal(normalize().publisher,"社区开发者");
  c.state.installedMetadata = new Map();
  const stale = deferred();
  c.fetch = ()=>stale.promise;
  const oldLoad = c.loadInstalledMetadata();
  c.state.installedMetadata = new Map();
  stale.resolve(response("author = Stale Author"));
  await oldLoad;
  assert.equal(normalize().publisher,"社区开发者");
  c.state.system.installed_apps = Array.from({length:7},(_,i)=>({id:"app"+i,source:"sd",version:"1"}));
  c.updateNormalizedApps();
  const batch = deferred();
  let count = 0;
  c.fetch = ()=>{count++;return batch.promise;};
  const loading = c.loadInstalledMetadata();
  await c.loadInstalledMetadata();
  assert.equal(count,3);
  batch.resolve(response("author = Tester"));
  await loading;
  assert.equal(count,7);
  console.log("PASS: authors, metadata, escaping, fallbacks, version cache, stale requests, bounded concurrency");
}
main().catch((err)=>{console.error(err);process.exitCode=1;});
